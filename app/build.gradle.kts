val signingProperties = Properties().apply {
    val propertiesFile = rootProject.file("keystore.properties")
    if (propertiesFile.isFile) {
        propertiesFile.inputStream().use(::load)
    }
}

fun signingValue(propertyName: String, environmentName: String): String? =
    signingProperties.getProperty(propertyName)
        ?: providers.gradleProperty(environmentName).orNull
        ?: providers.environmentVariable(environmentName).orNull

val releaseStoreFile = signingValue("storeFile", "VINE_HELPER_KEYSTORE_PATH")
val releaseStorePassword = signingValue("storePassword", "VINE_HELPER_STORE_PASSWORD")
val releaseKeyAlias = signingValue("keyAlias", "VINE_HELPER_KEY_ALIAS")
val releaseKeyPassword = signingValue("keyPassword", "VINE_HELPER_KEY_PASSWORD")
val hasReleaseSigning = listOf(
    releaseStoreFile,
    releaseStorePassword,
    releaseKeyAlias,
    releaseKeyPassword
).all { !it.isNullOrBlank() }

